# Makes the laptop talk, using macOS's built-in `say` command.
# Audio goes to whatever output macOS is using, so plug the hamburger
# speaker into the headphone jack and it comes out of the speaker.

import logging
import shutil
import subprocess
from typing import Optional

logger = logging.getLogger(__name__)


class Speaker:
    def __init__(self, quiet: bool) -> None:
        # quiet=True prints "[SAY] ..." instead of speaking. Use it while
        # you're working on the code so the buddy doesn't yell at your team.
        self._quiet = quiet

        # The `say` process currently running, if any.
        self._current: Optional[subprocess.Popen] = None

        # shutil.which finds the full path of a command, like typing
        # `which say` in the terminal. Returns None if it doesn't exist
        # (for example on Linux), so we can fall back instead of crashing.
        self._say_path = shutil.which("say")
        if self._say_path is None and not quiet:
            logger.warning("'say' command not found, will print instead of speaking")

    def speak(self, text: str) -> None:
        if self._quiet or self._say_path is None:
            print(f"[SAY] {text}", flush=True)
            return

        # poll() returns None while the process is still running.
        # Don't start a second voice on top of the first one.
        if self._current is not None and self._current.poll() is None:
            logger.info("Still speaking, skipping new line")
            return

        # Popen starts `say` in the background and returns immediately,
        # so the server keeps answering hooks while the laptop talks.
        # The command is a LIST, not one string: the text is passed as a
        # single argument and never interpreted by a shell. That matters
        # later, when the lines are generated by an AI and could contain
        # characters like ; or $( ) that a shell would run as commands.
        self._current = subprocess.Popen([self._say_path, text])

    def stop(self) -> None:
        # Cut the voice off mid-sentence (used when you send a new prompt).
        if self._current is not None and self._current.poll() is None:
            self._current.terminate()
        self._current = None
