# Turns the voice clips (laptop/buddy/sounds/*.mp3) into C arrays the STM32
# can play through its DAC, and writes them to:
#   firmware/Claude-buddy/Core/Src/audio_clips.c
#   firmware/Claude-buddy/Core/Inc/audio_clips.h
#
# Run it on the Mac (it uses macOS's built-in `afconvert`) whenever a clip
# changes, then rebuild and flash the firmware:
#   python3 firmware/tools/make_audio_clips.py
#
# Format on the chip: 8000 samples per second, 1 byte per sample, unsigned
# (0 = lowest voltage, 128 = middle/silence, 255 = highest voltage).

import math
import os
import subprocess
import tempfile
import wave
from array import array

# Paths, relative to this file (firmware/tools/).
HERE = os.path.dirname(os.path.abspath(__file__))
SOUNDS_DIR = os.path.join(HERE, "..", "..", "laptop", "buddy", "sounds")
OUT_C = os.path.join(HERE, "..", "Claude-buddy", "Core", "Src", "audio_clips.c")
OUT_H = os.path.join(HERE, "..", "Claude-buddy", "Core", "Inc", "audio_clips.h")

# Must match AUDIO_SAMPLE_RATE in audio.c.
SAMPLE_RATE = 8000

# How loud, from 0 to 1. 1.0 swings the DAC over its full 0 to 3.3 V range,
# which is louder than a normal headphone signal and can distort the
# speaker's amplifier. 0.6 is about 2 V peak to peak. Raise it if too quiet.
VOLUME = 0.6

# Fade in and out over this many seconds, so clips don't start or end with a click.
FADE_SECONDS = 0.01

# The test beep played at startup: proves the wiring works.
BEEP_HZ = 880
BEEP_SECONDS = 0.25


def mp3_to_samples(mp3_path: str) -> array:
    # afconvert decodes the MP3 into a WAV file: mono (-c 1), 16-bit signed
    # little-endian (LEI16) at 8000 samples per second.
    with tempfile.TemporaryDirectory() as tmp:
        wav_path = os.path.join(tmp, "clip.wav")
        subprocess.run(
            ["afconvert", "-f", "WAVE", "-d", f"LEI16@{SAMPLE_RATE}", "-c", "1", mp3_path, wav_path],
            check=True,
        )
        with wave.open(wav_path, "rb") as wav:
            raw = wav.readframes(wav.getnframes())
    # array("h") = signed 16-bit numbers, -32768 to 32767.
    samples = array("h")
    samples.frombytes(raw)
    return samples


def beep_samples() -> array:
    # A plain sine wave at BEEP_HZ, at full 16-bit loudness.
    samples = array("h")
    count = int(BEEP_SECONDS * SAMPLE_RATE)
    for i in range(count):
        value = math.sin(2 * math.pi * BEEP_HZ * i / SAMPLE_RATE)
        samples.append(int(value * 32000))
    return samples


def to_dac_bytes(samples: array) -> bytearray:
    # 1. Find the loudest point, so every clip ends up equally loud.
    peak = 1
    for s in samples:
        if abs(s) > peak:
            peak = abs(s)

    fade_count = int(FADE_SECONDS * SAMPLE_RATE)
    out = bytearray()
    for i in range(len(samples)):
        # 2. Scale to -1..1, then by VOLUME.
        value = samples[i] / peak * VOLUME
        # 3. Fade in at the start and out at the end.
        if i < fade_count:
            value = value * i / fade_count
        frames_left = len(samples) - 1 - i
        if frames_left < fade_count:
            value = value * frames_left / fade_count
        # 4. -1..1 -> 0..255, with silence at 128.
        byte = int(round(128 + value * 127))
        out.append(max(0, min(255, byte)))
    return out


def c_array(name: str, data: bytearray) -> str:
    # One "const uint8_t name[] = { ... };", 24 numbers per line.
    # const puts it in flash (2 MB), not RAM (640 KB).
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for start in range(0, len(data), 24):
        chunk = data[start:start + 24]
        numbers = []
        for b in chunk:
            numbers.append(str(b))
        lines.append("  " + ",".join(numbers) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    # Every .mp3 in the sounds folder becomes a clip named after the file
    # ("yay.mp3" -> "yay"), plus the test beep.
    clips = [("beep", to_dac_bytes(beep_samples()))]
    for file_name in sorted(os.listdir(SOUNDS_DIR)):
        if file_name.endswith(".mp3"):
            name = file_name[:-4]
            clips.append((name, to_dac_bytes(mp3_to_samples(os.path.join(SOUNDS_DIR, file_name)))))

    parts = [
        "/* audio_clips.c - GENERATED by firmware/tools/make_audio_clips.py. Do not edit;",
        " * change the MP3s in laptop/buddy/sounds/ and run the script again. */",
        '#include "audio_clips.h"',
        "",
    ]
    total = 0
    for name, data in clips:
        parts.append(c_array(f"clip_{name}", data))
        parts.append("")
        total += len(data)

    parts.append("const AudioClip AUDIO_CLIPS[] = {")
    for name, data in clips:
        parts.append(f'  {{"{name}", clip_{name}, sizeof(clip_{name})}},')
    parts.append("};")
    parts.append(f"const uint32_t AUDIO_CLIP_COUNT = {len(clips)};")
    with open(OUT_C, "w") as f:
        f.write("\n".join(parts) + "\n")

    header = """/* audio_clips.h - GENERATED by firmware/tools/make_audio_clips.py. Do not edit. */
#ifndef AUDIO_CLIPS_H
#define AUDIO_CLIPS_H

#include <stdint.h>

/* One voice clip: 8000 samples per second, 1 byte each, 128 = silence. */
typedef struct {
  const char *name;       /* "yay", "done", ... (the MP3 name without .mp3) */
  const uint8_t *data;    /* the samples, stored in flash                   */
  uint32_t length;        /* number of samples                              */
} AudioClip;

extern const AudioClip AUDIO_CLIPS[];
extern const uint32_t AUDIO_CLIP_COUNT;

#endif /* AUDIO_CLIPS_H */
"""
    with open(OUT_H, "w") as f:
        f.write(header)

    for name, data in clips:
        print(f"  {name:<10} {len(data) / SAMPLE_RATE:4.1f} s")
    print(f"Total {total / 1024:.0f} KB of flash, {len(clips)} clips -> {os.path.relpath(OUT_C)}")


if __name__ == "__main__":
    main()
